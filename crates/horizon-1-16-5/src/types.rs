//! Shared 1.16.5 data types used by the world-file reader, resource-pack
//! baker and chunk mesher. They are deliberately independent of the 26.3
//! engine's block/registry types.

use serde_json::Value;
use std::borrow::Borrow;
use std::collections::{BTreeMap, HashMap};
use std::path::Path;

use crate::inventory::ItemStack;

pub type Properties = BTreeMap<String, String>;

/// One block state: the namespaced block id plus its property values.
#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct BlockState {
    pub name: String,
    pub properties: Properties,
}

impl BlockState {
    pub fn new(name: impl Into<String>) -> Self {
        Self {
            name: name.into(),
            properties: Properties::new(),
        }
    }
}

/// A source of named block states, addressed by world block coordinates.
pub trait BlockSource {
    fn state_at(&self, x: i32, y: i32, z: i32) -> Option<BlockState>;
}

/// The six box faces, in the order used by 1.16.5 block models.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Face {
    Down,
    Up,
    North,
    South,
    West,
    East,
}

impl Face {
    pub const ALL: [Self; 6] = [
        Self::Down,
        Self::Up,
        Self::North,
        Self::South,
        Self::West,
        Self::East,
    ];

    pub fn normal(self) -> [f32; 3] {
        match self {
            Self::Down => [0.0, -1.0, 0.0],
            Self::Up => [0.0, 1.0, 0.0],
            Self::North => [0.0, 0.0, -1.0],
            Self::South => [0.0, 0.0, 1.0],
            Self::West => [-1.0, 0.0, 0.0],
            Self::East => [1.0, 0.0, 0.0],
        }
    }

    pub fn opposite(self) -> Self {
        match self {
            Self::Down => Self::Up,
            Self::Up => Self::Down,
            Self::North => Self::South,
            Self::South => Self::North,
            Self::West => Self::East,
            Self::East => Self::West,
        }
    }

    pub fn offset(self) -> [i32; 3] {
        match self {
            Self::Down => [0, -1, 0],
            Self::Up => [0, 1, 0],
            Self::North => [0, 0, -1],
            Self::South => [0, 0, 1],
            Self::West => [-1, 0, 0],
            Self::East => [1, 0, 0],
        }
    }
}

/// One mesh vertex. Positions are in block units; UVs are model-space 0..16.
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct Vertex {
    pub position: [f32; 3],
    pub uv: [f32; 2],
    pub normal: [f32; 3],
}

/// A textured quad. `cullface` is the neighbor direction that can hide it.
#[derive(Clone, Debug, PartialEq)]
pub struct Quad {
    pub vertices: [Vertex; 4],
    pub texture: String,
    pub cullface: Option<Face>,
}

/// A baked model: quads in model space (0..16) with texture references.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct BakedModel {
    pub quads: Vec<Quad>,
}

/// Resolves a named block state to its baked model.
pub trait ModelSource {
    fn model(&self, state: &BlockState) -> Option<BakedModel>;
}

/// A CPU chunk mesh ready for a renderer upload.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct Mesh {
    pub vertices: Vec<Vertex>,
    pub indices: Vec<u32>,
    /// One texture name per emitted quad, in quad order. The indexes are
    /// two triangles per quad, so `textures[triangle_index / 2]` is the
    /// material of that triangle.
    pub textures: Vec<String>,
}

/// The 1.16.5 block-state table generated by `tools/prepare_1165.py`,
/// indexed both by numeric id and by the exact name/property combination.
#[derive(Clone, Debug, Default)]
pub struct BlockTable {
    states: Vec<BlockState>,
    ids: HashMap<BlockState, u16>,
}

impl BlockTable {
    pub fn load(path: &Path) -> Result<Self, String> {
        let bytes = std::fs::read(path).map_err(|error| format!("{}: {error}", path.display()))?;
        let json: Value = serde_json::from_slice(&bytes)
            .map_err(|error| format!("{}: {error}", path.display()))?;
        if json.get("version").and_then(Value::as_str) != Some("1.16.5") {
            return Err("block table is not for Minecraft 1.16.5".into());
        }
        let entries = json
            .get("blocks")
            .and_then(|blocks| blocks.get("entries"))
            .and_then(Value::as_object)
            .ok_or("block table has no blocks.entries")?;
        let mut states = Vec::new();
        let mut ids = HashMap::new();
        for (name, block) in entries {
            let values = block
                .get("states")
                .and_then(Value::as_array)
                .ok_or_else(|| format!("block {name} has no states"))?;
            for state in values {
                let id = state
                    .get("id")
                    .and_then(Value::as_i64)
                    .and_then(|id| usize::try_from(id).ok())
                    .ok_or_else(|| format!("block {name} has an invalid state id"))?;
                if id > usize::from(u16::MAX) {
                    return Err(format!("block state id {id} does not fit the 1.16.5 table"));
                }
                let mut properties = Properties::new();
                if let Some(values) = state.get("properties").and_then(Value::as_object) {
                    for (key, value) in values {
                        let value = match value {
                            Value::String(text) => text.clone(),
                            Value::Bool(flag) => flag.to_string(),
                            Value::Number(number) => number.to_string(),
                            _ => return Err(format!("block {name} has a non-scalar property")),
                        };
                        properties.insert(key.clone(), value);
                    }
                }
                if states.len() <= id {
                    states.resize(id + 1, BlockState::new(""));
                }
                let block_state = BlockState {
                    name: name.clone(),
                    properties,
                };
                if !states[id].name.is_empty() || ids.contains_key(&block_state) {
                    return Err(format!("duplicate block state id or key at {id}"));
                }
                states[id] = block_state.clone();
                ids.insert(block_state, id as u16);
            }
        }
        Ok(Self { states, ids })
    }

    pub fn state(&self, id: u16) -> Option<&BlockState> {
        self.states
            .get(usize::from(id))
            .filter(|state| !state.name.is_empty())
    }

    pub fn state_id(&self, state: &BlockState) -> Option<u16> {
        self.ids.get(state).copied()
    }

    /// The lowest-id state of a block, by name.
    ///
    /// The name may be bare (`stone`) or namespaced (`minecraft:stone`); a
    /// bare name is read as `minecraft:<name>`. Returns `None` when the
    /// table has no state with that name.
    pub fn first_state(&self, name: &str) -> Option<BlockState> {
        let full = if name.contains(':') {
            name.to_owned()
        } else {
            format!("minecraft:{name}")
        };
        self.states.iter().find(|state| state.name == full).cloned()
    }

    /// The default state of a block, by name.
    ///
    /// The table does not store the `default` flag, so this is the lowest-id
    /// state of the block: the same state `first_state` returns.
    pub fn default_state(&self, name: &str) -> Option<BlockState> {
        self.first_state(name)
    }

    /// The item a mined `block` drops when no loot table overrides it.
    ///
    /// In 1.16.5 most blocks drop themselves, so this is the block's own item
    /// name. A name the table does not know drops nothing. This is the same
    /// membership test [`BlockTable::first_state`] uses and needs no zip data.
    pub fn loot_for(&self, block: &str) -> Vec<ItemStack> {
        match self.first_state(block) {
            Some(state) => vec![ItemStack::new(state.name, 1)],
            None => Vec::new(),
        }
    }

    /// The drops for a block broken while holding `holding`.
    ///
    /// `holding` is accepted for callers that already have the selected stack;
    /// the block-table fallback does not vary with the tool, so it only feeds
    /// loot-table aware callers. Either an owned stack or a reference to one
    /// may be passed.
    pub fn harvest_drop<T: Borrow<ItemStack>>(
        &self,
        block: &str,
        holding: Option<T>,
    ) -> Vec<ItemStack> {
        let _ = holding;
        self.loot_for(block)
    }

    pub fn len(&self) -> usize {
        self.states.len()
    }

    pub fn is_empty(&self) -> bool {
        self.states.is_empty()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn block_table_round_trips_ids_and_properties() {
        let json = serde_json::json!({
            "version": "1.16.5",
            "blocks": {"entries": {
                "minecraft:air": {"states": [{"id": 0, "default": true}]},
                "minecraft:oak_log": {"states": [
                    {"id": 1, "properties": {"axis": "x"}},
                    {"id": 2, "properties": {"axis": "y"}, "default": true},
                ]},
            }},
        });
        let path = std::env::temp_dir().join(format!(
            "horizon-1-16-5-table-{}-{}.json",
            std::process::id(),
            std::thread::current().name().unwrap_or("test")
        ));
        std::fs::write(&path, serde_json::to_vec(&json).unwrap()).unwrap();
        let table = BlockTable::load(&path).unwrap();
        std::fs::remove_file(&path).unwrap();
        assert_eq!(table.len(), 3);
        let axis_y = BlockState {
            name: "minecraft:oak_log".into(),
            properties: [("axis".to_owned(), "y".to_owned())].into_iter().collect(),
        };
        assert_eq!(table.state_id(&axis_y), Some(2));
        assert_eq!(table.state(1).unwrap().properties["axis"], "x");
        assert!(table.state(3).is_none());
    }

    #[test]
    fn block_table_rejects_duplicate_ids_and_wrong_versions() {
        for (version, blocks) in [
            (
                "26.3",
                serde_json::json!({"minecraft:air": {"states": [{"id": 0}]}}),
            ),
            (
                "1.16.5",
                serde_json::json!({"a": {"states": [{"id": 0}]}, "b": {"states": [{"id": 0}]}}),
            ),
        ] {
            let path = std::env::temp_dir().join(format!(
                "horizon-1-16-5-bad-table-{}-{}-{}.json",
                std::process::id(),
                version,
                blocks.to_string().len()
            ));
            std::fs::write(
                &path,
                serde_json::to_vec(
                    &serde_json::json!({"version": version, "blocks": {"entries": blocks}}),
                )
                .unwrap(),
            )
            .unwrap();
            assert!(BlockTable::load(&path).is_err());
            std::fs::remove_file(&path).unwrap();
        }
    }

    #[test]
    fn block_table_loot_falls_back_to_the_block_item() {
        let json = serde_json::json!({
            "version": "1.16.5",
            "blocks": {"entries": {
                "minecraft:stone": {"states": [{"id": 0, "default": true}]},
            }},
        });
        let path = std::env::temp_dir().join(format!(
            "horizon-1-16-5-loot-table-{}-{}.json",
            std::process::id(),
            std::thread::current().name().unwrap_or("test")
        ));
        std::fs::write(&path, serde_json::to_vec(&json).unwrap()).unwrap();
        let table = BlockTable::load(&path).unwrap();
        std::fs::remove_file(&path).unwrap();

        let stone = vec![ItemStack::new("minecraft:stone", 1)];
        assert_eq!(table.loot_for("minecraft:stone"), stone);
        assert_eq!(table.loot_for("stone"), stone);
        assert!(table.loot_for("minecraft:bedrock").is_empty());
        assert_eq!(
            table.harvest_drop("stone", Some(ItemStack::new("minecraft:iron_pickaxe", 1))),
            stone
        );
        let pickaxe = ItemStack::new("minecraft:diamond_pickaxe", 1);
        assert_eq!(table.harvest_drop("minecraft:stone", Some(&pickaxe)), stone);
        assert!(
            table
                .harvest_drop("minecraft:bedrock", None::<ItemStack>)
                .is_empty()
        );
    }
}
